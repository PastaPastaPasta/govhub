import assert from 'node:assert/strict';
import fs from 'node:fs';
import { chromium } from '../../../../../lab/node_modules/playwright/index.mjs';
import { installQaGuard } from '../../../../../lab/qa-guard.mjs';

const out = new URL('../../../../../shots/wip-c/', import.meta.url);
fs.mkdirSync(out, {recursive:true});
const report = {checks:[], parity:[], blocked:[], pageErrors:[], notes:['Live public reads; no synthetic chain data. Deep Gov URLs use the lab’s existing HTTP 404 SPA fallback.']};
const browser = await chromium.launch({headless:true,args:['--host-resolver-rules=MAP *.localhost 127.0.0.1','--disable-dev-shm-usage']});
const context = await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,locale:'en-US',timezoneId:'UTC',serviceWorkers:'block'});
await installQaGuard(context,{onBlocked:x=>report.blocked.push(x)});
const page = await context.newPage();
const requests = [];
page.on('request',r=>requests.push(r.url()));
page.on('pageerror',e=>report.pageErrors.push(e.message));
const gov = 'http://gov.dashhq.localhost:8787';
const vote = 'http://vote.dashhq.localhost:8787';
const check = (name, value) => {assert(value, name);report.checks.push(name);};
const go = async url => { await page.goto(url); await page.locator('dashhq-bar').waitFor(); };
const noOverflow = async () => check('Phone has no horizontal page overflow', await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth));
try {
  await go(gov);
  await page.locator('[data-testid="proposal-card"]').first().waitFor({timeout:45000});
  check('Read guard is present',await page.evaluate(()=>!!window.labReadPolicy));
  await noOverflow();
  await page.locator('.prow-title a').first().click();
  await page.locator('.p-vote-cta').waitFor({timeout:45000});
  check('Proposal exposes the voting-key journey',await page.getByRole('link',{name:'Add your voting key',exact:true}).isVisible());
  await page.getByRole('link',{name:'Add your voting key',exact:true}).click();
  await page.locator('.kr-gate').getByRole('button',{name:'Sign in',exact:true}).click();
  await page.locator('dialog.sheet[open]').waitFor();
  check('Adding a masternode reaches the sign-in sheet',await page.locator('dialog.sheet[open]').isVisible());
  await noOverflow();
  await page.locator('dialog.sheet').getByRole('button',{name:'Close',exact:true}).click();
  await page.getByRole('button',{name:'Menu',exact:true}).click();
  await page.getByRole('link',{name:'Name contests',exact:true}).filter({visible:true}).click();
  await page.waitForURL('**/names');
  await page.getByRole('heading',{name:'Name contests',exact:true}).waitFor();
  check('Phone nav reaches name contests',await page.getByRole('heading',{name:'Name contests',exact:true}).isVisible());
  await go(gov+'/?network=testnet');
  check('Gov shell shows Testnet',await page.locator('dashhq-bar').getAttribute('network')==='testnet');
  await page.getByRole('button',{name:'Menu',exact:true}).click();
  const names = page.getByRole('link',{name:'Name contests',exact:true}).filter({visible:true});
  check('Gov internal links preserve Testnet',(await names.getAttribute('href')).includes('network=testnet'));
  await names.click();
  await page.waitForURL('**/names?network=testnet');
  await page.getByRole('button',{name:'Network: Testnet',exact:true}).click();
  await page.getByRole('link',{name:'Mainnet',exact:true}).filter({visible:true}).click();
  await page.waitForURL(gov+'/names');
  await page.waitForFunction(()=>document.querySelector('dashhq-bar')?.getAttribute('network')==='mainnet');
  check('Shell network switch changes URL and profile',await page.locator('dashhq-bar').getAttribute('network')==='mainnet');
  await go(gov+'/?network=testnet&profile=dev');
  check('Mixed profile says which data and Platform network it uses',await page.getByText('Mainnet proposals · Testnet Platform.',{exact:true}).isVisible());
  await noOverflow();
  await go(gov+'/masternodes');
  check('Keyring journey remains available',await page.getByRole('heading',{name:/masternodes/i}).first().isVisible());
  await go(vote+'/?network=testnet#/c/german');
  const handoff = page.locator('.handoff a');
  check('Vote contest handoff carries label and network',(await handoff.getAttribute('href'))===gov+'/names/german?network=testnet');
  await handoff.click();
  await page.waitForURL(gov+'/names/german?network=testnet');
  check('Gov actually serves the contest route',await page.locator('dashhq-bar').getAttribute('product')==='gov');
  await go(vote+'/#/about');
  check('About works without waiting for Platform',await page.getByRole('heading',{name:'About EvoVote'}).isVisible());
  check('Receipts guidance is visible',await page.getByText(/vote receipts stay/).isVisible());
  await noOverflow();
  await go(vote);
  await page.locator('.ledger-row').first().waitFor({timeout:60000});
  const labels = await page.locator('.ledger-row').evaluateAll(links=>links.slice(0,5).map(a=>decodeURIComponent(a.getAttribute('href').split('/c/')[1])));
  for (const label of labels) {
    await go(vote+'/#/c/'+encodeURIComponent(label));
    await page.locator('.contenders').waitFor({timeout:45000});
    await page.locator('.contest-meta .chip').filter({hasText:/closes in|awarded|locked|decided|voting closed/}).waitFor({timeout:45000});
    const legacy = await page.locator('.contender-tally .tally-number, .alt-choice .tally-number').allTextContents();
    const legacyDeadline = await page.locator('.contest-meta').innerText();
    const href = await page.locator('.handoff a').getAttribute('href');
    await page.locator('.handoff a').click();
    await page.waitForURL(href);
    const ready = await page.locator('[data-testid="contest-page"]').waitFor({timeout:45000}).then(()=>true,()=>false);
    if (!ready) {report.parity.push({label,legacy,legacyDeadline,error:await page.locator('main').innerText()});continue;}
    const canonical = await page.locator('.c-choice .c-tally b').allTextContents();
    const canonicalDeadline = await page.locator('[data-testid="contest-status"]').innerText();
    check('Tallies match for '+label,JSON.stringify(legacy)===JSON.stringify(canonical));
    const absoluteDeadline = legacyDeadline.split(' · ')[1]?.split('\n')[0];
    check('Closing time matches for '+label,!!absoluteDeadline && canonicalDeadline.includes(absoluteDeadline));
    report.parity.push({label,legacy,canonical,legacyDeadline,canonicalDeadline});
    await noOverflow();
    if (label===labels[0]) {
      await page.getByTestId('guest-open').click();
      check('Contest guest voting-key form remains available',await page.getByTestId('guest-key').getAttribute('data-masked')==='true');
      check('Empty voting-key form cannot submit',await page.getByTestId('guest-find').isDisabled());
      await page.getByRole('button',{name:'Show voters',exact:true}).first().click();
      await page.locator('.contest-voters').waitFor({timeout:45000});
      const explorer = page.locator('.c-ident .author-name').first();
      check('Contender identity links to lab Explorer',(await explorer.getAttribute('href')).startsWith('http://explorer.dashhq.localhost:8787/identity?id='));
      await page.screenshot({path:new URL('gov-contest-phone.png',out).pathname});
      await explorer.click();
      await page.waitForURL(url=>url.hostname==='explorer.dashhq.localhost' && url.pathname.replace(/\/$/,'')==='/identity');
      check('Explorer cross-link can be followed',new URL(page.url()).hostname==='explorer.dashhq.localhost');
    }
  }
  check('Five live contests checked',report.parity.length===5 && report.parity.every(x=>!x.error));
  await context.newPage().then(async phone => { await phone.setViewportSize({width:360,height:800}); await phone.goto(gov); await phone.locator('dashhq-bar').waitFor(); check('Gov fits a 360px phone',await phone.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)); await phone.goto(vote); await phone.locator('dashhq-bar').waitFor(); check('Vote fits a 360px phone',await phone.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)); await phone.close(); });
  check('No Google Fonts requests',!requests.some(u=>/fonts\.(googleapis|gstatic)\.com/.test(u)));
  check('No page exceptions',report.pageErrors.length===0);
} finally {
  fs.writeFileSync(new URL('journeys.json',out),JSON.stringify(report,null,2)+'\n');
  await browser.close();
}
console.log(JSON.stringify(report,null,2));
