#!/bin/sh
# govhub dashd wrapper. Replaces the image's /docker-entrypoint.sh (which only execs its arguments).
#
# Builds /tmp/dash.conf from the mounted template plus environment and secrets, then execs dashd.
# /tmp is container-local, so the RPC password never lands on a volume or in an image layer.
#
# Environment (all optional unless noted; compose sets them from .env):
#   DASH_NETWORK        mainnet | testnet | regtest             (default mainnet)
#   CORE_RPC_USER       RPC user name                           (default govhub)
#   RPC_PASSWORD_FILE   file with the RPC password              (default /run/secrets/core_rpc_password)
#   RPC_ALLOW_CIDR      who may call RPC, besides localhost     (default 172.29.73.0/24)
#   DASHD_DBCACHE_MB    -dbcache in MiB                         (default 1024)
#   DASHD_MAXCONNECTIONS  -maxconnections                       (default: Core's)
#   DASHD_P2P_PORT      -port; set it in .env if you publish P2P (default: the network's)
#   DASHD_EXTERNALIP    -externalip, the address you announce   (default: none)
#   DASHD_EXTRA_ARGS    extra dashd command-line flags, word-split
set -eu
umask 077

CONF=/tmp/dash.conf
TEMPLATE=/etc/govhub/dash.conf
NETWORK="${DASH_NETWORK:-mainnet}"
RPC_USER="${CORE_RPC_USER:-govhub}"
PW_FILE="${RPC_PASSWORD_FILE:-/run/secrets/core_rpc_password}"

if [ ! -r "$TEMPLATE" ]; then
  echo "govhub-dashd: cannot read $TEMPLATE" >&2
  exit 1
fi
if [ ! -r "$PW_FILE" ]; then
  echo "govhub-dashd: cannot read RPC password file $PW_FILE (run deploy/scripts/init.sh; on Linux the file must be readable by uid 1000)" >&2
  exit 1
fi
RPC_PASSWORD="$(tr -d '\r\n' < "$PW_FILE")"
if [ -z "$RPC_PASSWORD" ]; then
  echo "govhub-dashd: $PW_FILE is empty" >&2
  exit 1
fi

# The password is written to a conf file, one `key=value` per line. Reject anything that could
# smuggle in a second option or break dash.conf parsing.
case "$RPC_USER$RPC_PASSWORD" in
  *'#'* | *' '* | *'"'* | *"'"* | *\\* | *'$'*)
    echo "govhub-dashd: RPC user/password must not contain spaces, quotes, #, \\ or \$ (init.sh generates a safe one)" >&2
    exit 1
    ;;
esac

cp "$TEMPLATE" "$CONF"
{
  printf '\n# ---- generated by govhub entrypoint ----\n'
  # Core only honors rpcport, rpcbind, port and friends inside the network's own section.
  case "$NETWORK" in
    mainnet) echo '[main]' ;;
    testnet) echo 'testnet=1'; echo '[test]' ;;
    regtest) echo 'regtest=1'; echo '[regtest]' ;;
    *)
      echo "govhub-dashd: DASH_NETWORK must be mainnet, testnet or regtest (got '$NETWORK')" >&2
      exit 1
      ;;
  esac
  echo 'rpcport=9998'
  echo 'rpcbind=0.0.0.0'
  echo "rpcuser=$RPC_USER"
  echo "rpcpassword=$RPC_PASSWORD"
  echo "rpcallowip=${RPC_ALLOW_CIDR:-172.29.73.0/24}"
  echo "dbcache=${DASHD_DBCACHE_MB:-1024}"
  [ -n "${DASHD_MAXCONNECTIONS:-}" ] && echo "maxconnections=$DASHD_MAXCONNECTIONS"
  [ -n "${DASHD_P2P_PORT:-}" ] && echo "port=$DASHD_P2P_PORT"
  [ -n "${DASHD_EXTERNALIP:-}" ] && echo "externalip=$DASHD_EXTERNALIP"
  if [ "$NETWORK" = regtest ]; then
    # An isolated chain: no inbound listener needed, nothing to connect to.
    echo 'listen=0'
  fi
} >> "$CONF"

# shellcheck disable=SC2086  # DASHD_EXTRA_ARGS is deliberately word-split
exec dashd -conf="$CONF" ${DASHD_EXTRA_ARGS:-}
