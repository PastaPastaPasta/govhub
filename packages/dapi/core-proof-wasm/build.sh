#!/usr/bin/env bash
# Builds ../src/vendor/core-proof-wasm.ts (inline base64 of the verifier module) from this crate: a C-ABI wrapper (src/lib.rs) around
# dash-core-proof, the DIP 175 quorum proof chain verifier of dashpay/platform PR #5521, vendored unmodified in vendor/dash-core-proof
# (see its Cargo.toml for the upstream commit). The module has no imports.
# Toolchain: rustup stable with the wasm32-unknown-unknown target; Homebrew LLVM clang + llvm-ar for the C parts (blst, rs-x11-hash);
# binaryen wasm-opt. Override with LLVM_BIN=, WASM_OPT=, OPT=Oz|O3, CARGO_TARGET_DIR=, WASM_OUT=<path to also keep the .wasm>.
set -euo pipefail
cd "$(dirname "$0")"

LLVM_BIN=${LLVM_BIN:-/opt/homebrew/opt/llvm/bin}
WASM_OPT=${WASM_OPT:-/opt/homebrew/bin/wasm-opt}
OPT=${OPT:-Oz}
OUT_TS=${OUT_TS:-../src/vendor/core-proof-wasm.ts}
export CARGO_TARGET_DIR=${CARGO_TARGET_DIR:-$PWD/target}
export PATH="$LLVM_BIN:$PATH"
export CC_wasm32_unknown_unknown=clang AR_wasm32_unknown_unknown=llvm-ar

cargo build --locked --release --target wasm32-unknown-unknown
RAW="$CARGO_TARGET_DIR/wasm32-unknown-unknown/release/govhub_core_proof_wasm.wasm"
BUILD=$(mktemp -d "${TMPDIR:-/tmp}/core-proof-wasm.XXXXXX")
"$WASM_OPT" "-$OPT" --enable-bulk-memory --enable-sign-ext --enable-mutable-globals --enable-nontrapping-float-to-int \
  --strip-debug --strip-producers "$RAW" -o "$BUILD/core-proof.wasm"

SHA=$(shasum -a 256 "$BUILD/core-proof.wasm" | cut -d' ' -f1)
SIZE=$(wc -c < "$BUILD/core-proof.wasm" | tr -d ' ')
{
  echo "// GENERATED by core-proof-wasm/build.sh ($(rustc --version | cut -d' ' -f1-2), wasm-opt -$OPT). Do not edit. dash-core-proof (DIP 175) verifier; no imports."
  echo "// wasm sha256: $SHA ($SIZE bytes)"
  printf "export const CORE_PROOF_WASM_BASE64 = '%s';\n" "$(base64 < "$BUILD/core-proof.wasm" | tr -d '\n')"
} > "$OUT_TS"
[ -z "${WASM_OUT:-}" ] || cp "$BUILD/core-proof.wasm" "$WASM_OUT"
echo "wrote $OUT_TS"
echo "core-proof.wasm sha256 $SHA ($SIZE bytes, -$OPT)"
