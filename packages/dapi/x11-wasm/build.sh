#!/usr/bin/env bash
# Builds ../src/vendor/x11-wasm.ts (inline base64 of x11.wasm) from the sphlib C sources in this directory. No imports, no libc.
#
# Provenance (all MIT, Projet RNRT SAPHIR / Thomas Pornin, licence headers intact in every file):
#   Dash Core tree /Users/pasta/workspace/dash at f35a24cfca12, src/crypto/x11/:
#     blake.c bmw.c cubehash.c groestl.c jh.c keccak.c luffa.c simd.c skein.c and sph_{blake,bmw,cubehash,groestl,jh,keccak,luffa,simd,skein,types}.h  (HEAD)
#   echo.c, sph_echo.h, aes_helper.c : 7e8607e1cbfd^ (c4e7a40d842f), the last plain-C Echo-512 (before "remove large footprint Echo512 impl, switch to C++")
#   shavite.c, sph_shavite.h         : 386742b5fcaa^ (7e8607e1cbfd), the last plain-C Shavite-512 (before its C++/SIMD dispatch rewrite); aes_helper.c identical at both parents
#   The stage order is Core's HashX11, src/hash_x11.h:44-87 (see x11.c). compat/string.h is the only non-upstream header.
# Toolchain: Homebrew clang (wasm32 target) + rust-lld's wasm-ld + binaryen wasm-opt. Override with CLANG=, WASM_LD=, WASM_OPT=, OPT=Oz|O3 (wasm-opt level), FOOTPRINT=small|large, WASM_OUT=<path to also keep the .wasm>, BUILD_DIR=.
set -euo pipefail
cd "$(dirname "$0")"

CLANG=${CLANG:-/opt/homebrew/opt/llvm/bin/clang}
RUSTC_TC=${RUSTC_TC:-/Users/pasta/.rustup/toolchains/1.98-aarch64-apple-darwin}
WASM_LD=${WASM_LD:-$RUSTC_TC/lib/rustlib/aarch64-apple-darwin/bin/gcc-ld/wasm-ld}
WASM_OPT=${WASM_OPT:-/opt/homebrew/bin/wasm-opt}
OPT=${OPT:-Oz}
# FOOTPRINT=small (default): sphlib's rolled-loop variants, 85 KB / 39 KB gz, ~10 us/header. FOOTPRINT=large: unrolled, 190 KB / 69 KB gz, ~7.7 us/header.
FOOTPRINT=${FOOTPRINT:-small}
[ "$FOOTPRINT" = small ] && FP_FLAG=-DSPH_SMALL_FOOTPRINT=1 || FP_FLAG=-DSPH_SMALL_FOOTPRINT=0
CFLAGS_EXTRA=${CFLAGS_EXTRA:-}
OUT_TS=${OUT_TS:-../src/vendor/x11-wasm.ts}
BUILD=${BUILD_DIR:-$(mktemp -d "${TMPDIR:-/tmp}/x11-wasm.XXXXXX")}
mkdir -p "$BUILD"
export DYLD_FALLBACK_LIBRARY_PATH="$RUSTC_TC/lib${DYLD_FALLBACK_LIBRARY_PATH:+:$DYLD_FALLBACK_LIBRARY_PATH}"

SRCS=(x11 blake bmw groestl skein jh keccak luffa cubehash shavite simd echo)
# sph_types.h cannot detect wasm32: declare it little-endian with cheap unaligned access (wasm loads/stores never trap on alignment).
CC_OPT=${CC_OPT:--O3}
CFLAGS=(--target=wasm32 $CC_OPT -c -nostdlib -ffreestanding -mbulk-memory -Icompat -I. -w
        -DSPH_LITTLE_ENDIAN=1 -DSPH_UNALIGNED=1 -DSPH_UPTR=sph_u32 -fvisibility=hidden $FP_FLAG $CFLAGS_EXTRA)
OBJS=()
for s in "${SRCS[@]}"; do
  # sphlib's rolled-loop Groestl-512 (SPH_SMALL_FOOTPRINT_GROESTL) produces wrong digests in this configuration (found by comparing every
  # stage with the unrolled build and the JS oracle; cause not investigated), so Groestl always uses the table-per-rotation path.
  extra=(); [ "$s" = groestl ] && extra=(-DSPH_SMALL_FOOTPRINT_GROESTL=0)
  "$CLANG" "${CFLAGS[@]}" ${extra[@]+"${extra[@]}"} "$s.c" -o "$BUILD/$s.o"; OBJS+=("$BUILD/$s.o")
done

"$WASM_LD" --no-entry --strip-all --gc-sections -z stack-size=65536 --initial-memory=262144 \
  --export=x11_hash --export=x11_batch --export=x11_buf --export=x11_stage \
  "${OBJS[@]}" -o "$BUILD/x11.raw.wasm"

"$WASM_OPT" "-$OPT" --enable-bulk-memory --enable-sign-ext --enable-mutable-globals --enable-nontrapping-float-to-int \
  ${WASM_OPT_EXTRA:-} --strip-debug --strip-producers "$BUILD/x11.raw.wasm" -o "$BUILD/x11.wasm"

SHA=$(shasum -a 256 "$BUILD/x11.wasm" | cut -d' ' -f1)
SIZE=$(wc -c < "$BUILD/x11.wasm" | tr -d ' ')
{
  echo "// GENERATED by x11-wasm/build.sh (footprint: $FOOTPRINT, wasm-opt -$OPT). Do not edit. X11 (Dash block hash) from the sphlib C sources; no imports."
  echo "// wasm sha256: $SHA ($SIZE bytes)"
  printf "export const X11_WASM_BASE64 = '%s';\n" "$(base64 < "$BUILD/x11.wasm" | tr -d '\n')"
} > "$OUT_TS"
[ -z "${WASM_OUT:-}" ] || cp "$BUILD/x11.wasm" "$WASM_OUT"
echo "wrote $OUT_TS"
echo "x11.wasm sha256 $SHA ($SIZE bytes, $FOOTPRINT, -$OPT)"
