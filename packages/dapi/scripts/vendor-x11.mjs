// Generates src/vendor/x11/*.js from @dashevo/x11-hash-js (devDependency, pinned): ESM conversion + one bug fix.
//   node scripts/vendor-x11.mjs
//
// Why vendor instead of importing the package: its groestl.js (the only file without 'use strict') calls
// `this.hi` inside a plain function (B64), which is only harmless in sloppy mode. Any ES-module bundler output is strict, so
// `x11(header)` throws "Cannot read properties of undefined (reading 'hi')" in every browser bundle (found by the live test).
// The fix is `x.hi` (what the line clearly means; the value is masked away in the sloppy case, so hashes are unchanged).
// test/x11-vendor.test.ts proves the vendored copy equals the original on random inputs for every stage.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, copyFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkgDir = dirname(createRequire(join(root, 'package.json')).resolve('@dashevo/x11-hash-js/package.json'));
const version = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')).version;
const out = join(root, 'src/vendor/x11');
mkdirSync(out, { recursive: true });

const stages = ['blake', 'bmw', 'groestl', 'skein', 'jh', 'luffa', 'cubehash', 'shavite', 'simd', 'echo'];
for (const f of readdirSync(join(pkgDir, 'lib'))) {
  let src = readFileSync(join(pkgDir, 'lib', f), 'utf8');
  src = src.replace(/^'use strict';\s*/m, '');
  const imports = [];
  src = src.replace(/^var (\w+) = require\('\.\/(\w+)(?:\.js)?'\);\s*$/gm, (_, name, mod) => { imports.push(`import ${name} from './${mod}.js';`); return ''; });
  if (/\brequire\(/.test(src.replace(/^\s*\/\/.*$/gm, ''))) throw new Error(`${f}: unconverted require()`);
  if (f === 'groestl.js') {
    const before = src;
    src = src.replace('this.hi << bitsOff32 >>> bitsOff32', 'x.hi << bitsOff32 >>> bitsOff32');
    if (src === before) throw new Error('groestl.js: expected `this.hi` bug not found (package changed? re-audit before updating)');
  }
  writeFileSync(join(out, f), [
    `// Generated by scripts/vendor-x11.mjs from @dashevo/x11-hash-js@${version} (MIT, see LICENSE). Do not edit.`,
    ...imports, 'const module = { exports: {} };', src.trim(), 'export default module.exports;', '',
  ].join('\n'));
}

writeFileSync(join(out, 'x11.js'), `// Generated by scripts/vendor-x11.mjs. The X11 chain exactly as @dashevo/x11-hash-js/index.js digest(input, 1, 1) runs it.
import blake from './blake.js';
import bmw from './bmw.js';
import groestl from './groestl.js';
import skein from './skein.js';
import jh from './jh.js';
import keccak from './keccak.js';
import luffa from './luffa.js';
import cubehash from './cubehash.js';
import shavite from './shavite.js';
import simd from './simd.js';
import echo from './echo.js';
import h from './helper.js';

/** @param {number[]} bytes @returns {number[]} 32 bytes (internal order) */
export function digest(bytes) {
  let a = blake(bytes, 1, 2);
  a = bmw(a, 2, 2);
  a = groestl(a, 2, 2);
  a = skein(a, 2, 2);
  a = jh(a, 2, 2);
  a = keccak.keccak_512.array(h.int32Buffer2Bytes(a));
  a = luffa(a, 1, 2);
  a = cubehash(a, 2, 2);
  a = shavite(a, 2, 2);
  a = simd(a, 2, 2);
  a = echo(a, 2, 2);
  return h.int32Buffer2Bytes(a.slice(0, 8));
}
export const stages = { ${stages.join(', ')} };
`);
writeFileSync(join(out, 'x11.d.ts'), `export function digest(bytes: number[]): number[];
type Stage = (input: number[], inputFormat: 1 | 2, outputFormat: 1 | 2) => number[];
export const stages: Record<'${stages.join("' | '")}', Stage>;
`);
copyFileSync(join(pkgDir, 'LICENSE'), join(out, 'LICENSE'));
console.log(`vendored @dashevo/x11-hash-js@${version} -> src/vendor/x11 (${readdirSync(out).length} files)`);
